import {readdirSync,readFileSync} from 'node:fs';
import {join} from 'node:path';
const root=new URL('..',import.meta.url).pathname;
const files=readdirSync(join(root,'web/src'));
if(files.some(file=>!['main.jsx','style.css'].includes(file)))throw Error('Application behavior belongs in Rust; web/src contains only the JS entry point and CSS.');
for(const directory of ['crates/board-core/src','crates/web/src'])for(const file of readdirSync(join(root,directory))){if(/\.(js|jsx|d\.ts)$/.test(file)&&!readFileSync(join(root,directory,file),'utf8').startsWith('// Generated by rust-js'))throw Error('Generated source was replaced by handwritten JS: '+file);}
console.log('Rust application source boundary checked.');
